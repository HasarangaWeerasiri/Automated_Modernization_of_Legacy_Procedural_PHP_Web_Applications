"""Write docs/c2-apps-results.md: Component 2's results on the whole rule-discovery apps.

Reads only what tools/harness/run_apps.py wrote under output/apps/<app>/: index.json and each
page's stage2.json and stage5.json. Nothing is recomputed, so the same commit and outputs always
give byte-identical Markdown.

Usage, from component2_frontend/ (after tools/harness/run_apps.py):
    venv/Scripts/python.exe tools/apps_results_table.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from results_table import source  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "output" / "apps"
DEFAULT_MARKDOWN = ROOT / "docs" / "c2-apps-results.md"
APPS = ("hms", "wackopicko")


def _walk(node):
    yield node
    for child in node["children"]:
        yield from _walk(child)


def page_row(folder: Path, entry: dict) -> dict:
    """One page's numbers, from its stage outputs."""
    row = {"key": entry["key"], "path": entry["path"], "function": entry["function"], "nodes": entry["nodes"],
           "crash": entry["crash"], "tsc": entry["tsc"]}
    if entry["crash"]:
        return row
    stage2 = json.loads((folder / entry["key"] / "stage2.json").read_text(encoding="utf-8"))
    stage5 = json.loads((folder / entry["key"] / "stage5.json").read_text(encoding="utf-8"))
    abstains = {}
    for node in _walk(stage2["tree"]):
        if node["status"] == "abstain":
            abstains[node["reason"]] = abstains.get(node["reason"], 0) + 1
    severity = stage5["counts"]["severity"]
    row |= {"components": stage2["counts"]["components"], "abstain": stage2["counts"]["abstain"],
            "abstains": dict(sorted(abstains.items())), "review": stage2["counts"]["review"],
            "todo": severity["todo"], "s5review": severity["review"], "info": severity["info"],
            "nesting": sum(f["flag"] == "html_nesting_changed" for f in stage5["flags"])}
    return row


def name(row: dict) -> str:
    return f"`{row['path']}`" + (f" · `{row['function']}()`" if row["function"] else "")


def abstain_cell(row: dict) -> str:
    if not row["abstain"]:
        return "0"
    return f"{row['abstain']} (" + ", ".join(f"{reason} {n}" for reason, n in row["abstains"].items()) + ")"


def render(output: Path = OUTPUT, markdown: Path = DEFAULT_MARKDOWN) -> str:
    lines = [
        "# Component 2 — results on whole apps (harness)",
        "",
        f"Generated by `tools/apps_results_table.py` from the outputs of `tools/harness/run_apps.py`, "
        f"{source(markdown)}. **Input comes from the C2 test harness, not from Member 01's core**: no labels (every "
        "node is unlabelled, so Stage 2 marks it `review`), no contract and no endpoint map (every page is "
        "`no_endpoint`). The numbers show that whole apps run through Stages 1–5; they are not migration quality.",
        "",
    ]
    totals = []
    for app in APPS:
        index = json.loads((output / app / "index.json").read_text(encoding="utf-8"))
        rows = [page_row(output / app, entry) for entry in index["pages"]]
        ran = [r for r in rows if not r["crash"]]
        lines += [
            f"## {app} (commit `{index['sourceCommit'][:7]}`)",
            "",
            f"{index['files']} PHP files (libraries excluded) → {len(rows)} timelines: "
            f"{sum(r['function'] is None for r in rows)} pages and {sum(r['function'] is not None for r in rows)} "
            f"functions that print. {len(index['silentFiles'])} files print nothing at their top level. "
            f"{len(index['parseErrors'])} parse errors, {sum(bool(r['crash']) for r in rows)} crashes.",
            "",
            "| Page / function | Nodes | S2 components | S2 abstain (by reason) | S2 review | S5 todo | S5 review | "
            "S5 info | tsc errors | Nesting flags |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            if r["crash"]:
                lines.append(f"| {name(r)} | {r['nodes']} | **crash**: {r['crash']['error']} | | | | | | | |")
                continue
            tsc = "not run" if r["tsc"] is None else str(r["tsc"])
            lines.append(f"| {name(r)} | {r['nodes']} | {r['components']} | {abstain_cell(r)} | {r['review']} | "
                         f"{r['todo']} | {r['s5review']} | {r['info']} | {tsc} | {r['nesting']} |")
        total = {key: sum(r[key] for r in ran) for key in ("nodes", "components", "abstain", "review", "todo",
                                                            "s5review", "info", "nesting")}
        reasons = {}
        for r in ran:
            for reason, n in r["abstains"].items():
                reasons[reason] = reasons.get(reason, 0) + n
        tsc_known = all(r["tsc"] is not None for r in ran)
        total |= {"abstains": dict(sorted(reasons.items())), "tsc": sum(r["tsc"] or 0 for r in ran),
                  "timelines": len(rows), "crashes": sum(bool(r["crash"]) for r in rows),
                  "compiling": sum(r["tsc"] == 0 for r in ran), "tscKnown": tsc_known, "app": app}
        totals.append(total)
        lines.append(f"| **{app} total** | {total['nodes']} | {total['components']} | {abstain_cell(total)} | "
                     f"{total['review']} | {total['todo']} | {total['s5review']} | {total['info']} | "
                     f"{total['tsc'] if tsc_known else 'not run for every page'} | {total['nesting']} |")
        lines.append("")
    lines += [
        "## Totals per app",
        "",
        "| App | Timelines | Crashes | Compiling (0 strict tsc errors) | Nodes | S2 components | S2 abstain | S2 review | "
        "S5 todo | S5 review | S5 info | Flag rate | Nesting flags |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for t in totals:
        compiling = f"{t['compiling']}/{t['timelines']}" if t["tscKnown"] else "not run"
        lines.append(f"| {t['app']} | {t['timelines']} | {t['crashes']} | {compiling} | {t['nodes']} | "
                     f"{t['components']} | {abstain_cell(t)} | {t['review']} | {t['todo']} | {t['s5review']} | "
                     f"{t['info']} | {t['todo'] + t['s5review']} | {t['nesting']} |")
    lines += [
        "",
        "Flag rate = S5 todo + S5 review (generation-spec v0.4 §12). S2 review is high by construction: with no "
        "labels every loop and `if` is `unlabelled`. tsc errors come from one strict `tsc --noEmit` run per app "
        "over all its pages (`tools/compile_check.py`).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    markdown = Path(argv[0]) if argv else DEFAULT_MARKDOWN
    text = render(OUTPUT, markdown)
    markdown.parent.mkdir(parents=True, exist_ok=True)
    with markdown.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {markdown}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
