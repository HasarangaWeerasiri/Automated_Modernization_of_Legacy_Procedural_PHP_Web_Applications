# ---------------------------------------------------------------- figures (deterministic SVG)


def value(fact_id: str) -> str:
    return next(f for f in facts.all_facts() if f.id == fact_id).value()


def number(fact_id: str) -> float:
    found = re.match(r"\s*(\d+(?:\.\d+)?)", value(fact_id))
    if not found:
        raise ValueError(f"{fact_id}: no number in {value(fact_id)!r}")
    return float(found.group(1))


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def svg(width: int, height: int, body: list[str], title: str) -> str:
    return "\n".join([f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
                      f'viewBox="0 0 {width} {height}" font-family="Helvetica, Arial, sans-serif" font-size="12">',
                      f"<title>{esc(title)}</title>", f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
                      *body, "</svg>", ""])


def label_lines(label: str, x: float, y: float) -> str:
    """A group label, on two lines when it is long (split at the space nearest its middle)."""
    words = label.split(" ")
    if len(label) <= 18 or len(words) == 1:
        return f'<text x="{x:.1f}" y="{y}" text-anchor="middle" font-weight="bold">{esc(label)}</text>'
    cut = min(range(1, len(words)), key=lambda i: abs(len(" ".join(words[:i])) - len(label) / 2))
    first, second = " ".join(words[:cut]), " ".join(words[cut:])
    return (f'<text x="{x:.1f}" y="{y}" text-anchor="middle" font-weight="bold">{esc(first)}'
            f'<tspan x="{x:.1f}" dy="15">{esc(second)}</tspan></text>')


def bars(groups: list[tuple[str, list[tuple[str, float, str]]]], title: str, ymax: float, ticks: list[float],
         fmt=lambda v: f"{v:.3f}", min_width: int = 0) -> str:
    """Grouped vertical bars: groups = [(group label, [(bar label, value, colour)])]."""
    bar, gap, group_gap, left, top, plot_h = 34, 6, 40, 130, 50, 260
    content = left + sum(len(b) * (bar + gap) for _, b in groups) + group_gap * len(groups) + 20
    width = max(min_width, content)
    shift = (width - content) / 2  # bars centred when the canvas is wider than they need
    height = top + plot_h + 125
    body = [f'<text x="{width / 2:.0f}" y="24" text-anchor="middle" font-size="15" font-weight="bold">{esc(title)}</text>']
    for t in ticks:
        y = top + plot_h - plot_h * t / ymax
        body += [f'<line x1="{left}" y1="{y:.1f}" x2="{width - 10}" y2="{y:.1f}" stroke="#dddddd"/>',
                 f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end">{esc(fmt(t))}</text>']
    x = left + group_gap / 2 + shift
    for label, items in groups:
        start = x
        for name, v, colour in items:
            h = plot_h * v / ymax
            y = top + plot_h - h
            body += [f'<rect x="{x:.1f}" y="{y:.1f}" width="{bar}" height="{h:.1f}" fill="{colour}"/>',
                     f'<text x="{x + bar / 2:.1f}" y="{y - 4:.1f}" text-anchor="middle" font-size="10">{esc(fmt(v))}</text>',
                     f'<text x="{x + bar / 2:.1f}" y="{top + plot_h + 14}" text-anchor="end" font-size="10" '
                     f'transform="rotate(-40 {x + bar / 2:.1f} {top + plot_h + 14})">{esc(name)}</text>']
            x += bar + gap
        body.append(label_lines(label, (start + x - gap) / 2, top + plot_h + 96))
        x += group_gap
    body.append(f'<line x1="{left}" y1="{top + plot_h}" x2="{width - 10}" y2="{top + plot_h}" stroke="#333333"/>')
    return svg(int(width), int(height), body, title)


