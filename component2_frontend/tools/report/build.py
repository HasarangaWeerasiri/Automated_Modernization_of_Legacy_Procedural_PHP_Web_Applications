def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode("utf-8"))


def main(argv: list[str]) -> int:
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else ROOT / "docs" / "report"
    write(out / "appendix-E-decisions.md", appendix_e())
    write(out / "appendix-F-ai-use.md", appendix_f())
    for name, draw in FIGURES.items():
        write(out / "fig" / name, draw())
    print(f"wrote {out}/appendix-E-decisions.md, appendix-F-ai-use.md, fig/{', fig/'.join(FIGURES)}")
    return 0


