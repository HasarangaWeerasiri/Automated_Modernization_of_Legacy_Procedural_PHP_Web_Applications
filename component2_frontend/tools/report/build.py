def section(doc: str, heading: str) -> str:
    start = next(m for m in re.finditer(r"^(#+) (.*)$", doc, re.M) if heading in m.group(2))
    level = len(start.group(1))
    rest = doc[start.end():]
    end = next((m.start() for m in re.finditer(r"^(#+) ", rest, re.M) if len(m.group(1)) <= level), len(rest))
    return rest[:end]


def raw_tables(text: str) -> list[list[list[str]]]:
    """Markdown tables with their cells exactly as written (not stripped of bold)."""
    out, current = [], None
    for line in text.split("\n"):
        if line.startswith("|"):
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
            if all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                continue
            if current is None:
                current = []
                out.append(current)
            current.append(cells)
        else:
            current = None
    return out


def parse_date(value: str) -> datetime:
    return datetime.strptime(re.sub(r"\s+", " ", value.strip()), "%d %b %Y")


def decisions() -> list[dict]:
    rows = []
    for path, heading, (date_col, decision_col, reason_col) in LOGS:
        for table in raw_tables(section(facts.text(path), heading)):
            header = table[0]
            if date_col not in header or decision_col not in header:
                continue
            for order, cells in enumerate(table[1:]):
                entry = dict(zip(header, cells))
                rows.append({"date": parse_date(entry[date_col]), "dateText": entry[date_col], "document": path,
                             "decision": entry[decision_col],
                             "reason": entry[reason_col] if reason_col else "— (the log has no reason column)",
                             "order": order})
    # gold-standard-guide.md has no decision log: its version note is in its header (copied)
    guide = "docs/gold-standard-guide.md"
    note = facts.find(guide, r"\(v1\.1, 18 Oct: ([^)]+)\)")
    rows.append({"date": parse_date("18 Oct 2026"), "dateText": "18 Oct 2026", "document": guide,
                 "decision": f"v1.1: {note}", "reason": "— (version note in the header; the guide has no decision log)",
                 "order": 0})
    return sorted(rows, key=lambda r: (r["date"], [p for p, _, _ in LOGS].index(r["document"])
                                       if r["document"] in [p for p, _, _ in LOGS] else len(LOGS), r["order"]))


def appendix_e() -> str:
    rows = decisions()
    lines = ["# Appendix E — Consolidated decision log (Component 2)", "",
             "Generated by `tools/report/build.py` from the decision logs of the committed documents below, in date order "
             "(entries of one date keep their document's order). Every entry is **copied** from its log, not reworded.", "",
             "| Source | Section | Commit |", "|---|---|---|"]
    for path, heading, _ in LOGS:
        lines.append(f"| `{path}` | {heading} | {facts.commit(path)} |")
    lines.append(f"| `docs/gold-standard-guide.md` | header (no decision log) | {facts.commit('docs/gold-standard-guide.md')} |")
    lines += ["", f"{len(rows)} entries.", "", "| Date | Document | Decision | Reason |", "|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['dateText']} | `{Path(r['document']).name}` | {r['decision']} | {r['reason']} |")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- Appendix F: the commit record


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True,
                          encoding="utf-8").stdout


def commits() -> list[dict]:
    """Every commit that touches component2_frontend/, oldest first, with its AI-assisted-by line (if any)."""
    out = []
    log = git("log", "--reverse", "--date=short", "--format=%h%x1f%ad%x1f%s%x1f%(trailers:key=AI-assisted-by,valueonly)%x1e",
              "--", "component2_frontend")
    for record in log.split("\x1e"):
        record = record.strip("\n")
        if not record.strip():
            continue
        short, date, subject, trailer = (record.split("\x1f") + [""])[:4]
        out.append({"hash": short.strip(), "date": date, "subject": subject, "ai": trailer.strip()})
    return out


