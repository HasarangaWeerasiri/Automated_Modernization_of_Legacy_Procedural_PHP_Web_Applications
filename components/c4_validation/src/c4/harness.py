"""Stage 3 — harness generation.

Turns the oracle records into a pytest suite the migrated system keeps (SO6, FR9):
one readable test per scenario, with the expected values written out. The suite
runs on its own, outside this engine, needing only pytest, requests, SQLAlchemy,
DeepDiff and a database driver.

    generated/<app>/
        test_equivalence.py   one test per scenario
        c4_checks.py          the comparison rules, copied from this engine
        conftest.py           the API and database fixtures
        baseline.json         the data every test starts from
        requirements.txt

The comparison rules are copied as source text from the engine's own functions when
the suite is generated, so the suite and the engine judge in exactly the same way.

    python -m c4.harness
"""

from __future__ import annotations

import argparse
import inspect
import json
import pprint
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from c4 import capture, compare, containers, dbstate, scenarios
from c4.config import Config, ConfigError, load_config

TEMPLATES = Path(__file__).resolve().parents[2] / "templates"

# The engine's own rules, copied into the suite as they are.
_COPIED = (
    dbstate._plain,
    compare.normalise,
    compare._leaves,
    compare._values,
    compare._match,
    compare._plain_delta,
    compare.injection_effects,
    capture.outcome_of,
)

_CHECKS_HEADER = '''"""The comparison rules used by the generated equivalence suite.

Generated by the C4 validation engine. Do not edit: generate it again instead.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from datetime import date, datetime, time, timedelta
from decimal import Decimal
from typing import Any, Iterable

import pytest
from deepdiff import DeepDiff
from sqlalchemy import MetaData, select, text

_NUMBER = re.compile({number!r})

'''

REQUIREMENTS = """pytest
requests
SQLAlchemy
deepdiff
# The driver for the migrated system's database. For MySQL:
PyMySQL
cryptography
"""


class HarnessError(RuntimeError):
    """The suite cannot be generated."""


def _python(value: Any, indent: int = 0) -> str:
    """A value written as a Python literal, wrapped and indented to sit inside a call."""
    text = pprint.pformat(value, width=max(40, 96 - indent), sort_dicts=False)
    return text.replace("\n", "\n" + " " * indent)


def checks_source() -> str:
    """The suite's c4_checks.py: the engine's rules, then the suite's own runtime."""
    copied = "\n\n".join(inspect.getsource(function).rstrip() for function in _COPIED)
    runtime = (TEMPLATES / "c4_checks_runtime.py").read_text(encoding="utf-8")
    return _CHECKS_HEADER.format(number=compare._NUMBER.pattern) + copied + "\n\n\n" + runtime


def _test_for(scenario: dict[str, Any], record: dict[str, Any], oracle: str, skip: str | None) -> dict[str, Any]:
    request = scenario["migrated_request"]
    legacy = record["input"]
    test = {
        "name": re.sub(r"\W", "_", scenario["scenario_id"]),
        "kind": scenario["scenario_type"],
        "title": f"{record['endpoint_id']}, as {legacy['method']} {record['legacy_url']} answered it.",
        "oracle": oracle,
        "skip": skip,
        "method": request["method"],
        "path": request["path"],
        "params": request["params"] or {},
        "body": request["body"],
        "at": request["records_at"],
        "login": scenario.get("migrated_login"),
    }
    if scenario["scenario_type"] == "injection":
        behaviour, _ = compare.legacy_injection_behaviour(record, scenario)
        probe = scenario["values"][scenario["parameter"]]
        test["probe"] = probe
        test["placed"] = not compare._unplaced(scenario)
        test["description"] = textwrap.fill(
            f"Injection probe on '{scenario['parameter']}'. The legacy page was {behaviour} "
            "for this input; the migrated system must treat it as plain text.",
            width=84, subsequent_indent="    ",
        )
        return test

    excluded = record["excluded_fields"]
    test.update({
        "description": f"Scenario: {scenario['scenario_type']}, {scenario.get('case') or 'typical'}.",
        "outcome": record["legacy_response"]["outcome"],
        "records": record["legacy_response"]["records"],
        "delta": record["db_state"]["delta"],
        "excluded_response": tuple(e["field"] for e in excluded if e["scope"] == "response"),
        "excluded_database": tuple(e["field"] for e in excluded if e["scope"] == "database"),
    })
    return test


def build(config: Config, baseline: dbstate.Snapshot) -> Path:
    """Write the suite for every captured scenario of the benchmark."""
    cases = []
    for scenario in scenarios.load_all(config):
        stored = config.oracle_dir / f"{scenario['scenario_id']}.json"
        if stored.is_file():
            cases.append((scenario, json.loads(stored.read_text(encoding="utf-8")), stored))
    if not cases:
        raise HarnessError("No oracle records yet: run python -m c4.capture first.")

    conflicting = compare.conflicts([(s, r) for s, r, _ in cases if s["scenario_type"] != "injection"])
    records = {scenario["scenario_id"]: record for scenario, record, _ in cases}
    tests = []
    for scenario, record, stored in cases:
        skip = None
        if scenario["scenario_id"] in conflicting:
            others = ", ".join(sorted(conflicting[scenario["scenario_id"]]))
            skip = f"Two legacy pages expect different results for this request (also: {others})."
        if scenario["scenario_type"] == "injection":
            reason = compare.not_judged(record, scenario, records.get(scenario.get("base")))
            if reason:
                skip = f"Not judged: {reason}."
        tests.append(_test_for(scenario, record, stored.relative_to(config.root).as_posix(), skip))

    environment = Environment(
        loader=FileSystemLoader(TEMPLATES), undefined=StrictUndefined,
        keep_trailing_newline=True, autoescape=False,
    )
    environment.filters["py"] = _python
    files = {
        "test_equivalence.py": environment.get_template("test_equivalence.py.j2").render(
            benchmark=config.benchmark, count=len(tests), tests=tests,
        ),
        "conftest.py": environment.get_template("conftest.py.j2").render(
            benchmark=config.benchmark, default_api_url=config.migrated.base_url,
            db_name=config.migrated.db_name,
        ),
        "c4_checks.py": checks_source(),
        "baseline.json": json.dumps({
            "tables": {name: list(table.rows) for name, table in baseline.tables.items()},
            "auto_increment": {
                name: table.auto_increment for name, table in baseline.tables.items() if table.auto_increment
            },
        }, indent=2, ensure_ascii=False) + "\n",
        "requirements.txt": REQUIREMENTS,
    }
    config.generated_dir.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (config.generated_dir / name).write_text(content, encoding="utf-8", newline="\n")
    return config.generated_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m c4.harness", description="Generate the equivalence test suite.")
    parser.add_argument("--benchmark", help="benchmark name; defaults to C4_BENCHMARK")
    args = parser.parse_args(argv)
    try:
        config = load_config(args.benchmark)
        containers.wait_until_ready(config, timeout=0)
        folder = build(config, dbstate.reset(config.migrated))
    except (
        ConfigError, HarnessError, scenarios.EndpointMapError, scenarios.ScenarioError,
        containers.DockerUnavailableError, containers.NotReadyError,
        dbstate.BaselineError, dbstate.ResetError,
    ) as error:
        print(error, file=sys.stderr)
        return 1
    tests = (folder / "test_equivalence.py").read_text(encoding="utf-8").count("\ndef test_")
    print(f"benchmark: {config.benchmark}")
    print(f"  {tests} tests -> {folder.relative_to(config.root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
