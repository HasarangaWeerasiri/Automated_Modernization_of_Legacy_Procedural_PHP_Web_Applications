def dependency_order(tables: list[dict]) -> tuple[list[str], list[tuple[str, dict]]]:
    """
    Order tables so that referenced tables are created first.

    Returns (ordered table names, deferred foreign keys). A foreign key is
    deferred (added after all tables exist) only when it is part of a
    cycle between different tables; self-references stay inline.
    Ties are broken by the order in the schema, so output is deterministic.
    """

    names = [table["name"] for table in tables]
    known = set(names)
    edges = {
        table["name"]: [
            fk for fk in table.get("foreign_keys", [])
            if fk["referenced_table"] in known and fk["referenced_table"] != table["name"]
        ]
        for table in tables
    }

    ordered: list[str] = []
    deferred: list[tuple[str, dict]] = []
    remaining = list(names)

    while remaining:
        ready = [
            name for name in remaining
            if all(fk["referenced_table"] in ordered for fk in edges[name])
        ]

        if not ready:
            # Cycle: create the first remaining table now and defer its
            # foreign keys to tables that do not exist yet.
            name = remaining[0]
            for fk in edges[name]:
                if fk["referenced_table"] not in ordered:
                    deferred.append((name, fk))
            edges[name] = [fk for fk in edges[name] if fk["referenced_table"] in ordered]
            ready = [name]

        for name in ready:
            ordered.append(name)
            remaining.remove(name)

    return ordered, deferred


def _foreign_key_constraint(fk: dict) -> str:
    arguments = [
        repr([fk["column"]]),
        repr([f"{fk['referenced_table']}.{fk['referenced_column']}"]),
    ]
    if fk.get("name"):
        arguments.append(f"name={fk['name']!r}")
    if fk.get("on_delete"):
        arguments.append(f"ondelete={fk['on_delete']!r}")
    if fk.get("on_update"):
        arguments.append(f"onupdate={fk['on_update']!r}")
    return f"ForeignKeyConstraint({', '.join(arguments)})"


def build_initial_revision(schema: dict) -> str:
    tables = schema.get("tables", [])
    by_name = {table["name"]: table for table in tables}
    ordered, deferred = dependency_order(tables)
    deferred_ids = {(name, fk["column"]) for name, fk in deferred}

    upgrade: list[str] = []
    downgrade: list[str] = []

    for name in ordered:
        table = by_name[name]
        # Column-level ForeignKey(...) is replaced by table-level constraints.
        plain = {**table, "foreign_keys": []}
        upgrade.append(f"    op.create_table(")
        upgrade.append(f"        {name!r},")

        for column in table.get("columns", []):
            arguments, _type = _column_arguments(plain, column)
            upgrade.append(f"        Column({column['name']!r}, {', '.join(arguments)}),")

        for constraint in _table_constraints(table):
            if constraint.startswith("Index("):
                continue
            upgrade.append(f"        {constraint},")

        for fk in table.get("foreign_keys", []):
            if fk["referenced_table"] in by_name and (name, fk["column"]) not in deferred_ids:
                upgrade.append(f"        {_foreign_key_constraint(fk)},")

        upgrade.append("    )")

        for index in table.get("indexes", []):
            index_name = index.get("name") or index["columns"][0]
            upgrade.append(f"    op.create_index({index_name!r}, {name!r}, {index['columns']!r})")

    for name, fk in deferred:
        constraint_name = fk.get("name") or f"fk_{name}_{fk['column']}"
        options = "".join(
            f", {key}={fk[value]!r}"
            for key, value in (("ondelete", "on_delete"), ("onupdate", "on_update"))
            if fk.get(value)
        )
        upgrade.append(
            f"    op.create_foreign_key({constraint_name!r}, {name!r}, "
            f"{fk['referenced_table']!r}, [{fk['column']!r}], "
            f"[{fk['referenced_column']!r}]{options})"
        )
        downgrade.append(f"    op.drop_constraint({constraint_name!r}, {name!r}, type_='foreignkey')")

    for name in reversed(ordered):
        downgrade.append(f"    op.drop_table({name!r})")

    notes = [
        f"#   {table['name']}: {feature}"
        for table in tables
        for feature in table.get("unsupported_features", [])
    ] + [f"#   {item}" for item in schema.get("unsupported_objects", [])]

    lines = [REVISION_HEADER.format(revision=REVISION), ""]

    if notes:
        lines.append("# Not migrated by this revision (see migration_notes.md):")
        lines.extend(notes)
        lines.append("")

    lines.append("")
    lines.append("def upgrade():")
    lines.extend(upgrade or ["    pass"])
    lines.append("")
    lines.append("")
    lines.append("def downgrade():")
    lines.extend(downgrade or ["    pass"])
    lines.append("")

    return "\n".join(lines)


def generate_alembic(
    schema_file: str | Path,
    alembic_dir: str | Path,
) -> list[Path]:
    """Write the Alembic environment and initial revision; return the files."""

    schema = load_schema(schema_file)
    alembic_dir = Path(alembic_dir)
    versions = alembic_dir / "versions"
    versions.mkdir(parents=True, exist_ok=True)

    files = {
        alembic_dir / "alembic.ini": ALEMBIC_INI,
        alembic_dir / "env.py": ENV_PY,
        alembic_dir / "script.py.mako": SCRIPT_MAKO,
        versions / f"{REVISION}.py": build_initial_revision(schema),
    }

    for path, content in files.items():
        path.write_text(content, encoding="utf-8")

    return list(files)
