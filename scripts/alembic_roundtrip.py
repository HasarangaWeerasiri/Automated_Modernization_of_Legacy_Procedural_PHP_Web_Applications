"""E3: Alembic round trip for one C3 output folder.

    upgrade head (on an EMPTY database)
    -> reflect the live database and compare with the generated models
       (tables, columns, nullability, primary keys, foreign keys, unique
       constraints, indexes)
    -> alembic check (autogenerate finds no pending differences)
    -> downgrade base (no application tables left)

Usage (repo root, project venv):
    python scripts/alembic_roundtrip.py <output_dir>/<app> --url <sqlalchemy url> --report <file.json>

The password is never passed on the command line: for MySQL use a URL
without password and set C3_DB_PASSWORD in the session.
Exit code 0 only when every step passes.
"""

import argparse
import importlib.util
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect
from sqlalchemy.engine import make_url


def _engine(url: str):
    parsed = make_url(url)
    if parsed.password is None and os.environ.get("C3_DB_PASSWORD") and parsed.get_backend_name() != "sqlite":
        parsed = parsed.set(password=os.environ["C3_DB_PASSWORD"])
    return create_engine(parsed)


def _load_models(models_file: Path):
    spec = importlib.util.spec_from_file_location("roundtrip_models", models_file)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.Base.metadata


def _norm(names):
    return sorted(name.lower() for name in names)


def compare_live_with_metadata(engine, metadata) -> list[dict]:
    """Differences between the live database and the model metadata."""

    inspector = inspect(engine)
    live_tables = {t.lower() for t in inspector.get_table_names()} - {"alembic_version"}
    diffs = []

    for missing in sorted({t.lower() for t in metadata.tables} - live_tables):
        diffs.append({"table": missing, "kind": "table_missing_in_database"})
    for extra in sorted(live_tables - {t.lower() for t in metadata.tables}):
        diffs.append({"table": extra, "kind": "table_not_in_models"})

    for table in metadata.sorted_tables:
        if table.name.lower() not in live_tables:
            continue

        live_columns = {c["name"].lower(): c for c in inspector.get_columns(table.name)}

        for column in table.columns:
            live = live_columns.get(column.name.lower())
            if live is None:
                diffs.append({"table": table.name, "kind": "column_missing", "column": column.name})
                continue
            if bool(live["nullable"]) != bool(column.nullable):
                diffs.append({"table": table.name, "kind": "nullability", "column": column.name,
                              "model": column.nullable, "database": live["nullable"]})

        live_pk = _norm(inspector.get_pk_constraint(table.name).get("constrained_columns") or [])
        if live_pk != _norm(c.name for c in table.primary_key.columns):
            diffs.append({"table": table.name, "kind": "primary_key", "database": live_pk})

        live_fks = sorted(
            (tuple(_norm(fk["constrained_columns"])), fk["referred_table"].lower(), tuple(_norm(fk["referred_columns"])))
            for fk in inspector.get_foreign_keys(table.name)
        )
        model_fks = sorted(
            (tuple(_norm(c.parent.name for c in fk.elements)), fk.referred_table.name.lower(),
             tuple(_norm(c.column.name for c in fk.elements)))
            for fk in table.foreign_key_constraints
        )
        if live_fks != model_fks:
            diffs.append({"table": table.name, "kind": "foreign_keys", "model": model_fks, "database": live_fks})

        live_unique = sorted(tuple(_norm(u["column_names"])) for u in inspector.get_unique_constraints(table.name))
        # MySQL reports UNIQUE constraints as unique indexes too.
        live_unique += sorted(
            tuple(_norm(i["column_names"])) for i in inspector.get_indexes(table.name) if i.get("unique")
        )
        model_unique = {tuple(_norm(c.name for c in u.columns)) for u in table.constraints
                        if u.__class__.__name__ == "UniqueConstraint"}
        model_unique |= {(c.name.lower(),) for c in table.columns if c.unique}
        missing_unique = sorted(model_unique - set(live_unique))
        if missing_unique:
            diffs.append({"table": table.name, "kind": "unique_missing_in_database", "columns": missing_unique})

        live_indexes = {tuple(_norm(i["column_names"])) for i in inspector.get_indexes(table.name) if not i.get("unique")}
        model_indexes = {tuple(_norm(c.name for c in i.columns)) for i in table.indexes}
        missing_indexes = sorted(model_indexes - live_indexes)
        if missing_indexes:
            diffs.append({"table": table.name, "kind": "index_missing_in_database", "columns": missing_indexes})

    return diffs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("app_output")
    parser.add_argument("--url", required=True)
    parser.add_argument("--report", required=True)
    args = parser.parse_args()

    app_output = Path(args.app_output).resolve()
    ini = app_output / "alembic" / "alembic.ini"
    os.environ["C3_ALEMBIC_URL"] = args.url
    engine = _engine(args.url)
    config = Config(str(ini))
    config.attributes["configure_logger"] = False

    result = {
        "app_output": app_output.name,
        "database": make_url(args.url).render_as_string(hide_password=True),
        "dialect": engine.dialect.name,
        "date_utc": datetime.now(timezone.utc).isoformat(),
        "steps": {},
    }

    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "components" / "c3_data_layer" / "src"))
    from c3.conversion.model_builder import mysql_only_defaults

    schema = json.loads((app_output / "schema.json").read_text(encoding="utf-8"))
    result["mysql_only_defaults"] = mysql_only_defaults(schema)

    if engine.dialect.name == "sqlite" and result["mysql_only_defaults"]:
        # The MySQL DDL is correct and is not altered to suit SQLite.
        result["verdict"] = "NOT_APPLICABLE_SQLITE_INCOMPATIBLE_MYSQL_DEFAULTS"
        result["note"] = "SQLite cannot execute these MySQL server defaults; run E3 on MySQL 8."
        Path(args.report).parent.mkdir(parents=True, exist_ok=True)
        Path(args.report).write_text(json.dumps(result, indent=2), encoding="utf-8")
        print(json.dumps({k: result[k] for k in ("app_output", "dialect", "verdict")}, indent=2))
        engine.dispose()
        return 0

    try:
        existing = set(inspect(engine).get_table_names()) - {"alembic_version"}
        if existing:
            raise RuntimeError(f"database is not empty: {sorted(existing)}")
        result["steps"]["database_empty_before"] = "PASS"

        command.upgrade(config, "head")
        result["steps"]["upgrade_head"] = "PASS"

        diffs = compare_live_with_metadata(engine, _load_models(app_output / "models.py"))
        result["schema_diffs"] = diffs
        result["steps"]["live_schema_matches_models"] = "PASS" if not diffs else "FAIL"

        try:
            command.check(config)
            result["steps"]["alembic_check"] = "PASS"
        except AutogenerateDiffsDetected as exc:
            result["steps"]["alembic_check"] = "FAIL"
            result["alembic_check_output"] = str(exc)

        command.downgrade(config, "base")
        left = set(inspect(engine).get_table_names()) - {"alembic_version"}
        result["steps"]["downgrade_base"] = "PASS" if not left else "FAIL"
        result["tables_left_after_downgrade"] = sorted(left)
    except Exception as exc:  # recorded, not hidden
        result["error"] = f"{type(exc).__name__}: {exc}"
    finally:
        engine.dispose()

    result["verdict"] = (
        "PASS" if not result.get("error") and all(v == "PASS" for v in result["steps"].values())
        and len(result["steps"]) == 5 else "FAIL"
    )

    Path(args.report).parent.mkdir(parents=True, exist_ok=True)
    Path(args.report).write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({k: result[k] for k in ("app_output", "dialect", "steps", "verdict")}, indent=2))
    if result.get("error"):
        print("ERROR:", result["error"], file=sys.stderr)
    return 0 if result["verdict"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
